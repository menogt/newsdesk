<?php
/**
 * Builds database/demo.sql = schema.sql + demonstration data from seed_data.php.
 * Dates are written relative to NOW()/CURDATE(), so the demo always looks
 * current on the day you import it.
 *
 * Usage:  php tools/build_demo_sql.php
 */
$root = dirname(__DIR__);
$data = require __DIR__ . '/seed_data.php';
$sql = [];
$q = fn($v) => $v === null ? 'NULL' : "'" . str_replace(["\\", "'"], ["\\\\", "''"], (string)$v) . "'";
$ago = fn(int $hours) => "NOW() - INTERVAL $hours HOUR";

$sql[] = file_get_contents("$root/database/schema.sql");
$sql[] = "\n-- ---------------------------------------------------------------\n-- Demonstration data (fictional). Generated by tools/build_demo_sql.php\n-- ---------------------------------------------------------------\n";

// Categories
$catIds = []; $i = 1;
foreach ($data['categories'] as $key => [$name, $desc, $color]) {
    $catIds[$key] = $i;
    $sql[] = "INSERT INTO categories (id, name, description, color, created_at) VALUES ($i, {$q($name)}, {$q($desc)}, {$q($color)}, NOW() - INTERVAL 150 DAY);";
    $i++;
}

// Users
$userIds = []; $i = 1;
foreach ($data['users'] as $key => [$name, $email, $password, $role, $days]) {
    $userIds[$key] = $i;
    $hash = password_hash($password, PASSWORD_DEFAULT);
    $last = $key === 'amaya' ? 'NULL' : 'NOW() - INTERVAL ' . (($i * 7) % 50 + 1) . ' HOUR';
    $sql[] = "INSERT INTO users (id, name, email, password_hash, role, status, created_at, last_login_at) VALUES ($i, {$q($name)}, {$q($email)}, {$q($hash)}, {$q($role)}, 'active', NOW() - INTERVAL $days DAY, $last);";
    $i++;
}

// Articles + daily views
$i = 1;
foreach ($data['articles'] as $a) {
    [$author, $cat, $kind, $status, $featured, $breaking, $hours, $views, $image, $expires, $title, $summary, $body] = $a;
    $img = $image ? "https://images.unsplash.com/$image?auto=format&fit=crop" : '';
    $published = $status === 'approved' ? $ago($hours) : 'NULL';
    $expiresSql = $expires === null ? 'NULL' : "CURDATE() + INTERVAL $expires DAY";
    $note = $status === 'rejected' ? 'Please add a proposed date, the teams involved and who is organising it.' : '';
    $sql[] = "INSERT INTO articles (id, author_id, category_id, title, summary, body, image, kind, status, featured, breaking, expires_at, review_note, views, created_at, updated_at, published_at) VALUES "
        . "($i, {$userIds[$author]}, {$catIds[$cat]}, {$q($title)}, {$q($summary)}, {$q($body)}, {$q($img)}, {$q($kind)}, {$q($status)}, $featured, $breaking, $expiresSql, {$q($note)}, $views, "
        . $ago($hours + 2) . ', ' . $ago($hours) . ", $published);";

    // Spread the total views over the days since publication, front-loaded like real news.
    if ($views > 0) {
        $age = max(0, intdiv($hours, 24));
        $weights = [];
        // $d = days since publication; most reads arrive in the first few days.
        for ($d = 0; $d <= $age; $d++) $weights[$d] = exp(-0.25 * $d) + 0.05;
        $sum = array_sum($weights); $left = $views; $values = [];
        foreach ($weights as $d => $w) { $values[$d] = (int)floor($views * $w / $sum); $left -= $values[$d]; }
        for ($k = 0; $left > 0; $k++, $left--) $values[$k % count($values)]++;
        $parts = [];
        foreach ($values as $d => $v) {
            if ($v > 0) $parts[] = "($i, CURDATE() - INTERVAL " . ($age - $d) . " DAY, $v)";
        }
        if ($parts) $sql[] = 'INSERT INTO article_views (article_id, view_date, views) VALUES ' . implode(', ', $parts) . ';';
    }
    $i++;
}

// Comments
foreach ($data['comments'] as [$user, $index, $status, $hours, $text]) {
    $sql[] = 'INSERT INTO comments (article_id, user_id, body, status, created_at) VALUES (' . ($index + 1) . ", {$userIds[$user]}, {$q($text)}, {$q($status)}, " . $ago($hours) . ');';
}
// Bookmarks
foreach ($data['bookmarks'] as [$user, $indexes]) {
    foreach ($indexes as $n => $index) $sql[] = "INSERT INTO bookmarks (user_id, article_id, created_at) VALUES ({$userIds[$user]}, " . ($index + 1) . ', NOW() - INTERVAL ' . (2 + $n * 5) . ' DAY);';
}
// Subscriptions
foreach ($data['subscriptions'] as [$user, $cats]) {
    foreach ($cats as $n => $cat) $sql[] = "INSERT INTO subscriptions (user_id, category_id, created_at) VALUES ({$userIds[$user]}, {$catIds[$cat]}, NOW() - INTERVAL " . (3 + $n * 6) . ' DAY);';
}
// Notifications
foreach ($data['notifications'] as [$user, $message, $index, $read, $hours]) {
    $link = $index >= 0 ? 'index.php?page=article&id=' . ($index + 1) : 'index.php?page=my_stories&status=rejected';
    $sql[] = "INSERT INTO notifications (user_id, message, link, is_read, created_at) VALUES ({$userIds[$user]}, {$q($message)}, {$q($link)}, $read, " . $ago($hours) . ');';
}

file_put_contents("$root/database/demo.sql", implode("\n", $sql) . "\n");
echo "Wrote database/demo.sql\n";
